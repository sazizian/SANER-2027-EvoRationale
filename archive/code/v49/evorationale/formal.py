"""Alloy 6.2 adapter with explicit, analyst-reviewed specifications.

No autogenerated dummy cardinality models and NO 'exit=0 => constraint holds'.
Only machine-readable solver SAT/UNSAT outcomes are accepted; otherwise UNKNOWN.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
import subprocess
import tempfile
from typing import Any


class NoAlloy:
    def analyze(self, state: dict[str, Any]) -> list[dict[str, Any]]:
        return [{"status": "NOT_EVALUATED", "applicable": bool(state.get("formal_constraints")),
                 "reason": "No formal analyzer configured"}] if state.get("formal_constraints") else []


class AlloyAnalyzer:
    """Invoke Alloy CLI using explicit models supplied/confirmed by the researcher.

    The tool must produce machine-readable results. Parser fails closed on unexpected
    output; the environment used for the paper must pin and smoke-test exact Alloy JAR.
    """
    def __init__(self, jar_path: str, timeout_seconds: int = 60, runner: Any = None) -> None:
        self.jar = Path(jar_path)
        if not self.jar.is_file():
            raise FileNotFoundError(self.jar)
        self.timeout = timeout_seconds
        self.runner = runner or subprocess.run

    def analyze(self, state: dict[str, Any]) -> list[dict[str, Any]]:
        results = []
        for spec in state.get("formal_constraints", []):
            for k in ("id", "element_id", "model", "command"):
                if not isinstance(spec.get(k), str) or not spec[k].strip():
                    raise ValueError(f"Missing formal specification field: {k}")
            if spec["element_id"] not in state["central_element_ids"] and spec["element_id"] not in {
                el["id"] for field in ("goals", "requirements", "assumptions", "original_evidence",
                                       "quality_attributes", "constraints_dependencies", "implementation_scope")
                for el in state.get(field, [])}:
                raise ValueError("Formal constraint refers to an unknown S0 element")
            model = spec["model"]
            with tempfile.TemporaryDirectory() as d:
                path = Path(d) / "model.als"
                path.write_text(model, encoding="utf-8")
                out = Path(d) / "output"
                out.mkdir()
                args = ["java", "-jar", str(self.jar.resolve()), "exec", "-c", spec["command"],
                        "-t", "json", "-o", str(out), "-f", str(path)]
                try:
                    p = self.runner(args, capture_output=True, text=True, timeout=self.timeout, check=False)
                    parsed = _parse_alloy_result(out, p.stdout, spec["command"]) if p.returncode == 0 else None
                    status = parsed or "UNKNOWN"
                    error = p.stderr[-600:] if p.returncode else ""
                except (OSError, subprocess.TimeoutExpired) as exc:
                    status, error = "UNKNOWN", type(exc).__name__
            results.append({"constraint_id": spec["id"], "element_id": spec["element_id"],
                            "command": spec["command"], "scope": spec.get("scope", "encoded_in_model"),
                            "model_sha256": hashlib.sha256(model.encode()).hexdigest(),
                            "status": status, "reason": error,
                            "semantic_note": ("For 'check', SAT means counterexample exists, UNSAT means none "
                                              "within the finite scope; solver result is not an architectural verdict.")})
        return results


def _parse_alloy_result(out_dir: Path, stdout: str, command: str) -> str | None:
    """Require an explicit command-associated JSON status, not a successful exit code."""
    candidates: list[Any] = []
    for p in out_dir.rglob("*.json"):
        if p.stat().st_size > 4_000_000:
            continue
        try:
            candidates.append(json.loads(p.read_text(encoding="utf-8")))
        except (ValueError, UnicodeError):
            continue
    try:
        candidates.append(json.loads(stdout))
    except (ValueError, TypeError):
        pass
    def seek(v: Any) -> str | None:
        if isinstance(v, dict):
            command_name = v.get("command") or v.get("name")
            value = v.get("status") or v.get("result")
            if command_name == command and isinstance(value, str) and value.upper() in {"SAT", "UNSAT"}:
                return value.upper()
            for value in v.values():
                found = seek(value)
                if found:
                    return found
        elif isinstance(v, list):
            for value in v:
                found = seek(value)
                if found:
                    return found
        return None
    for candidate in candidates:
        found = seek(candidate)
        if found:
            return found
    return None
